import fs from 'node:fs';
import path from 'node:path';

type Entry = { id: string; word: string; imgSrc: string };

function slugify(input: string) {
  return input
    .trim()
    .toLowerCase()
    .replace(/\.(png|jpg|jpeg|webp)$/i, '')
    .replace(/[_]+/g, '-')
    .replace(/[^a-z0-9-]+/g, '-')
    .replace(/-+/g, '-')
    .replace(/^-|-$/g, '');
}

function titleize(slug: string) {
  return slug
    .split('-')
    .filter(Boolean)
    .map((w) => w.slice(0, 1).toUpperCase() + w.slice(1))
    .join(' ');
}

const ROOT = process.cwd();
const PUBLIC_DIR = path.join(ROOT, 'public', 'thiings');
const OUT_FILE = path.join(ROOT, 'src', 'data', 'thiings100.ts');
const LIMIT = 100;

function main() {
  if (!fs.existsSync(PUBLIC_DIR)) {
    fs.mkdirSync(PUBLIC_DIR, { recursive: true });
  }

  const files = fs
    .readdirSync(PUBLIC_DIR)
    .filter((f) => /\.(png|jpg|jpeg|webp)$/i.test(f))
    .sort((a, b) => a.localeCompare(b));

  const picked = files.slice(0, LIMIT);
  const entries: Entry[] = picked.map((filename) => {
    const slug = slugify(filename);
    return {
      id: slug,
      word: titleize(slug),
      imgSrc: `/thiings/${filename}`,
    };
  });

  const banner = `/* eslint-disable */\n// This file is auto-generated by scripts/generate-thiings-dataset.ts\n// Place up to 100 PNG/JPG/WEBP files in public/thiings/, then run: npm run thiings:generate\n`;

  const body =
    banner +
    `\nexport type ThiingsEntry = { id: string; word: string; imgSrc: string };\n` +
    `\nexport const THIINGS_100: ThiingsEntry[] = ${JSON.stringify(entries, null, 2)} as const;\n`;

  const outDir = path.dirname(OUT_FILE);
  if (!fs.existsSync(outDir)) fs.mkdirSync(outDir, { recursive: true });
  fs.writeFileSync(OUT_FILE, body, 'utf8');

  // eslint-disable-next-line no-console
  console.log(`Generated ${entries.length} entries → ${path.relative(ROOT, OUT_FILE)}`);
}

main();

